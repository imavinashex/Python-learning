# Start with numbers = [5, 2, 9, 1, 7] and do the following:
# Sort the list in ascending order.
# Append the number 10 to the list.
# Remove the number 2 from the list.

number = [5, 2, 9, 1, 7]

number.sort()  # first using sort method to do this list to ascending order.
print(number)

number.append(10) # i add 10 in our list using append method.
print(number)

number.remove(2) # i removed number 2 in our list using remove method.
print(number)